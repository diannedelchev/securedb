// Outcome is what the SQL editor renders after a run.
type Outcome struct {
	RunID           string
	Status          string // success | error | blocked | pending_approval
	Message         string
	Result          *connectors.QueryResult
	MaskedColumns   map[int]string
	Decision        policies.Decision
	ApprovalRequest *approvals.Request
	DurationMS      int64
	// UsedGrant is set when an active PAM access window authorised a write
	// that would otherwise have required per-query approval.
	UsedGrant bool
}

type HistoryItem struct {
	ID             string
	ConnectionID   string
	ConnectionName string
	DatabaseName   string
	Environment    string
	UserEmail      string
	QueryText      string
	Status         string
	ErrorMessage   string
	RowCount       int
	DurationMS     int
	RiskScore      int
	CreatedAt      time.Time
}

// HistoryDay groups history items for the timeline view.
type HistoryDay struct {
	Label string
	Items []HistoryItem
}

// GroupByDay splits history items (already sorted desc) into day buckets.
func GroupByDay(items []HistoryItem) []HistoryDay {
	var out []HistoryDay
	today := time.Now().Local().Format("2006-01-02")
	yesterday := time.Now().Local().AddDate(0, 0, -1).Format("2006-01-02")
	for _, it := range items {
		day := it.CreatedAt.Local().Format("2006-01-02")
		label := strings.ToUpper(it.CreatedAt.Local().Format("Monday — January 2, 2006"))
		switch day {
		case today:
			label = "TODAY — " + strings.ToUpper(it.CreatedAt.Local().Format("January 2, 2006"))
		case yesterday:
			label = "YESTERDAY — " + strings.ToUpper(it.CreatedAt.Local().Format("January 2, 2006"))
		}
		if len(out) == 0 || out[len(out)-1].Label != label {
			out = append(out, HistoryDay{Label: label})
		}
		out[len(out)-1].Items = append(out[len(out)-1].Items, it)
	}
	return out
}

type SavedQuery struct {
	ID             string
	Name           string
	QueryText      string
	ConnectionID   string
	ConnectionName string
	CreatedAt      time.Time
}

// Service orchestrates policy evaluation, execution, masking, history and audit.
type Service struct {
	pool     *pgxpool.Pool
	conns    *connections.Service
	policies *policies.Service
	approv   *approvals.Service
	grants   *pam.Service
	audit    *audit.Logger

	mu      sync.Mutex
	running map[string]runHandle // runID -> cancel, for "Stop query"
}

type runHandle struct {
	cancel context.CancelFunc
	userID string
}

func NewService(pool *pgxpool.Pool, conns *connections.Service, pol *policies.Service,
	appr *approvals.Service, grants *pam.Service, aud *audit.Logger) *Service {
	return &Service{
		pool: pool, conns: conns, policies: pol, approv: appr, grants: grants, audit: aud,
		running: map[string]runHandle{},
	}
}

// Row-limit sentinels for ExecRequest.RowLimit.
const (
	RowLimitPolicyDefault = -1
	RowLimitUnlimited     = 0
)

type ExecRequest struct {
	User         *users.User
	ConnectionID string
	// Database selects which database on the connection's server to run
	// against; empty means the connection's default database.
	Database  string
	SQL       string
	Reason    string // used when the run turns into an approval request
	IP        string
	UserAgent string
	// Approved execution: run a previously approved request verbatim.
	ApprovalID string
	// RunID is generated by the client before submitting, so a parallel
	// "Stop query" request can cancel the run while it is still executing.
	RunID string
	// RowLimit caps fetched rows for read queries: a positive number, 0 for
	// unlimited (RowLimitUnlimited), or RowLimitPolicyDefault to use the
	// environment policy's max_rows.
	RowLimit int
}

// Execute runs the full pipeline for a user-submitted query.
func (s *Service) Execute(ctx context.Context, req ExecRequest) Outcome {
	conn, err := s.conns.Get(ctx, req.ConnectionID)
	if err != nil {
		return Outcome{Status: "error", Message: "connection not found"}
	}
	if !conn.IsActive {
		return Outcome{Status: "error", Message: "connection is inactive"}
	}
	// Multi-database: default to the connection's database, allow switching to
	// any other database on the same server (validated identifier only).
	database := req.Database
	if database == "" {
		database = conn.DatabaseName
	}
	if !connectors.ValidDatabaseName(database) {
		return Outcome{Status: "error", Message: fmt.Sprintf("invalid database name %q", database)}
	}

	policy, _ := s.policies.ForEnvironment(ctx, conn.Environment)
	decision := policies.Evaluate(policies.CheckInput{
		SQL:          req.SQL,
		IsAdmin:      req.User.IsAdmin(),
		IsPrivileged: req.User.IsPrivileged(),
		ConnReadOnly: conn.ReadOnly,
		Environment:  conn.Environment,
		Policy:       policy,
	})

	auditBase := audit.Entry{
		UserID: req.User.ID, ConnectionID: conn.ID, EntityType: "query",
		IP: req.IP, UserAgent: req.UserAgent, QueryText: req.SQL,
	}

	// PAM: an active just-in-time access window authorises writes on this
	// connection without per-query approval. Hard blocks (keywords, WHERE
	// rules, read-only) above still apply — those never bypass.
	usedGrant := false
	if decision.RequiresApproval && s.grants != nil && s.grants.HasActive(ctx, req.User.ID, conn.ID) {
		decision.RequiresApproval = false
		decision.Allowed = true
		usedGrant = true
	}

	// Approved re-execution bypasses the approval gate (the SQL was already
	// reviewed) but still honours all hard blocks. The approval is only valid
	// for the exact SQL and target database it was reviewed for.
	if req.ApprovalID != "" && decision.RequiresApproval {
		ar, err := s.approv.Get(ctx, req.ApprovalID)
		if err != nil || ar.UserID != req.User.ID || !ar.CanExecute() ||
			ar.QueryText != req.SQL || ar.DatabaseName != database {
			return Outcome{Status: "error", Message: "approval is not valid for this query"}
		}
		if err := s.approv.MarkExecuted(ctx, ar.ID); err != nil {
			return Outcome{Status: "error", Message: err.Error()}
		}
		decision.Allowed = true
		decision.RequiresApproval = false
	}

	if decision.RequiresApproval {
		ar, err := s.approv.Create(ctx, req.User.ID, conn.ID, database, conn.Environment, req.SQL, req.Reason, decision.RiskScore)
		if err != nil {
			return Outcome{Status: "error", Message: "could not create approval request: " + err.Error()}
		}
		s.recordHistory(ctx, req.User.ID, conn.ID, database, req.SQL, "pending_approval", "", 0, 0)
		e := auditBase
		e.Action = audit.ActionApprovalRequested
		e.EntityType = "approval_request"
		e.EntityID = ar.ID
		s.audit.Log(ctx, e)
		return Outcome{
			Status:          "pending_approval",
			Message:         decision.Reason,
			Decision:        decision,
			ApprovalRequest: ar,
		}
	}

	if !decision.Allowed {
		s.recordHistory(ctx, req.User.ID, conn.ID, database, req.SQL, "blocked", decision.Reason, 0, 0)
		e := auditBase
		e.Action = audit.ActionQueryBlocked
		e.Status = "blocked"
		e.ErrorMessage = decision.Reason
		s.audit.Log(ctx, e)
		return Outcome{Status: "blocked", Message: decision.Reason, Decision: decision}
	}

	cfg, err := s.conns.Config(conn)
	if err != nil {
		return Outcome{Status: "error", Message: err.Error(), Decision: decision}
	}
	cfg.Database = database
	connector, err := connectors.ForType(conn.DBType)
	if err != nil {
		return Outcome{Status: "error", Message: err.Error(), Decision: decision}
	}

	// Register a cancellable run so the UI can stop it. The client sends its
	// own run ID so the Stop button works while this request is in flight.
	runID := req.RunID
	if _, err := uuid.Parse(runID); err != nil {
		runID = uuid.NewString()
	}
	runCtx, cancel := context.WithCancel(context.WithoutCancel(ctx))
	s.mu.Lock()
	s.running[runID] = runHandle{cancel: cancel, userID: req.User.ID}
	s.mu.Unlock()
	defer func() {
		cancel()
		s.mu.Lock()
		delete(s.running, runID)
		s.mu.Unlock()
	}()

	timeout := time.Duration(policy.TimeoutSeconds) * time.Second
	// The editor's LIMIT selector chooses the row cap (100 / 500 / unlimited);
	// the policy's max_rows is only the fallback when the client sends none.
	maxRows := req.RowLimit
	if maxRows == RowLimitPolicyDefault {
		maxRows = policy.MaxRows
	}
	result, execErr := connector.ExecuteQuery(runCtx, cfg, connectors.QueryRequest{
		SQL:     req.SQL,
		MaxRows: maxRows,
		Timeout: timeout,
		IsWrite: decision.Analysis.IsWrite,
	})
	durationMS := result.Duration.Milliseconds()

	if execErr != nil {
		status := "error"
		msg := execErr.Error()
		if runCtx.Err() == context.Canceled {
			status = "cancelled"
			msg = "query cancelled"
		}
		s.recordHistory(ctx, req.User.ID, conn.ID, database, req.SQL, status, msg, 0, int(durationMS))
		e := auditBase
		e.Action = audit.ActionQueryExecuted
		e.Status = "failure"
		e.ErrorMessage = msg
		s.audit.Log(ctx, e)
		return Outcome{RunID: runID, Status: status, Message: msg, Decision: decision, DurationMS: durationMS}
	}

	// Data masking for read results.
	var maskedCols map[int]string
	if policy.MaskSensitiveColumns && len(result.Rows) > 0 {
		rules, err := s.policies.MaskingRules(ctx)
		if err != nil || len(rules) == 0 {
			rules = policies.DefaultMaskingRules()
			for i := range rules {
				rules[i].IsActive = true
			}
		}
		maskedCols = policies.ApplyMasking(rules, result.Columns, result.Rows)
	}

	rowCount := len(result.Rows)
	if decision.Analysis.IsWrite {
		rowCount = int(result.RowsAffected)
	}
	s.recordHistory(ctx, req.User.ID, conn.ID, database, req.SQL, "success", "", rowCount, int(durationMS))
	e := auditBase
	e.Action = audit.ActionQueryExecuted
	s.audit.Log(ctx, e)

	return Outcome{
		RunID:         runID,
		Status:        "success",
		Result:        &result,
		MaskedColumns: maskedCols,
		Decision:      decision,
		DurationMS:    durationMS,
		UsedGrant:     usedGrant,
	}
}

// Cancel stops a running query by run ID. Only the user who started the run
// (or an admin) may cancel it.
func (s *Service) Cancel(runID, userID string, isAdmin bool) bool {
	s.mu.Lock()
	defer s.mu.Unlock()
	if h, ok := s.running[runID]; ok && (h.userID == userID || isAdmin) {
		h.cancel()
		return true
	}
	return false
}

func (s *Service) recordHistory(ctx context.Context, userID, connID, database, sql, status, errMsg string, rows, durationMS int) {
	_, _ = s.pool.Exec(ctx,
		`INSERT INTO query_history (user_id, connection_id, database_name, query_text, status, error_message, row_count, duration_ms)
		 VALUES ($1,$2,$3,$4,$5,$6,$7,$8)`,
		userID, connID, database, sql, status, errMsg, rows, durationMS)
}

// History lists a user's recent queries; auditors/admins may view everyone's.
func (s *Service) History(ctx context.Context, userID string, all bool, limit int) ([]HistoryItem, error) {
	if limit <= 0 || limit > 500 {
		limit = 50
	}
	q := `SELECT h.id, COALESCE(c.id::text,''), COALESCE(c.name,''), h.database_name, COALESCE(c.environment,''),
	             u.email, h.query_text, h.status, h.error_message, h.row_count, h.duration_ms, h.created_at
	      FROM query_history h
	      JOIN users u ON u.id = h.user_id
	      LEFT JOIN database_connections c ON c.id=h.connection_id`
	args := []any{}
	if !all {
		args = append(args, userID)
		q += ` WHERE h.user_id=$1`
	}
	args = append(args, limit)
	q += fmt.Sprintf(` ORDER BY h.created_at DESC LIMIT $%d`, len(args))
	rows, err := s.pool.Query(ctx, q, args...)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []HistoryItem
	for rows.Next() {
		var h HistoryItem
		if err := rows.Scan(&h.ID, &h.ConnectionID, &h.ConnectionName, &h.DatabaseName, &h.Environment,
			&h.UserEmail, &h.QueryText, &h.Status, &h.ErrorMessage,
			&h.RowCount, &h.DurationMS, &h.CreatedAt); err != nil {
			return nil, err
		}
		h.RiskScore = policies.Risk(h.QueryText, h.Environment)
		out = append(out, h)
	}
	return out, rows.Err()
}

// SearchHistory finds the user's recent queries containing a term
// (case-insensitive substring), newest first — the topbar search source.
func (s *Service) SearchHistory(ctx context.Context, userID, term string, limit int) ([]HistoryItem, error) {
	if limit <= 0 || limit > 50 {
		limit = 8
	}
	rows, err := s.pool.Query(ctx,
		`SELECT h.id, COALESCE(c.id::text,''), COALESCE(c.name,''), h.database_name, COALESCE(c.environment,''),
		        u.email, h.query_text, h.status, h.error_message, h.row_count, h.duration_ms, h.created_at
		 FROM query_history h
		 JOIN users u ON u.id = h.user_id
		 LEFT JOIN database_connections c ON c.id=h.connection_id
		 WHERE h.user_id=$1 AND h.query_text ILIKE $2 ESCAPE '\'
		 ORDER BY h.created_at DESC LIMIT $3`,
		userID, "%"+escapeLike(term)+"%", limit)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []HistoryItem
	for rows.Next() {
		var h HistoryItem
		if err := rows.Scan(&h.ID, &h.ConnectionID, &h.ConnectionName, &h.DatabaseName, &h.Environment,
			&h.UserEmail, &h.QueryText, &h.Status, &h.ErrorMessage,
			&h.RowCount, &h.DurationMS, &h.CreatedAt); err != nil {
			return nil, err
		}
		out = append(out, h)
	}
	return out, rows.Err()
}

// escapeLike escapes ILIKE wildcards so the search term matches literally.
func escapeLike(s string) string {
	return strings.NewReplacer(`\`, `\\`, `%`, `\%`, `_`, `\_`).Replace(s)
}

func (s *Service) SaveQuery(ctx context.Context, userID, connectionID, name, sql string) error {
	if name == "" || sql == "" {
		return fmt.Errorf("name and query are required")
	}
	var connID any
	if connectionID != "" {
		connID = connectionID
	}
	_, err := s.pool.Exec(ctx,
		`INSERT INTO saved_queries (user_id, connection_id, name, query_text) VALUES ($1,$2,$3,$4)`,
		userID, connID, name, sql)
	return err
}

func (s *Service) SavedQueries(ctx context.Context, userID string) ([]SavedQuery, error) {
	rows, err := s.pool.Query(ctx,
		`SELECT s.id, s.name, s.query_text, COALESCE(s.connection_id::text,''), COALESCE(c.name,''), s.created_at
		 FROM saved_queries s LEFT JOIN database_connections c ON c.id=s.connection_id
		 WHERE s.user_id=$1 ORDER BY s.created_at DESC LIMIT 100`, userID)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []SavedQuery
	for rows.Next() {
		var sq SavedQuery
		if err := rows.Scan(&sq.ID, &sq.Name, &sq.QueryText, &sq.ConnectionID, &sq.ConnectionName, &sq.CreatedAt); err != nil {
			return nil, err
		}
		out = append(out, sq)
	}
	return out, rows.Err()
}

func (s *Service) DeleteSavedQuery(ctx context.Context, userID, id string) error {
	_, err := s.pool.Exec(ctx, `DELETE FROM saved_queries WHERE id=$1 AND user_id=$2`, id, userID)
	return err
}
